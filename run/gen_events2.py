def emit():
    out = []
    for name, eid, kinds, doc in EVENTS:
        ev = "EVENT_" + name.upper()
        sym = ""
        if kinds:
            pairs = ", ".join(f'{{ {k}, \\"{v}\\" }}' for k, v in kinds)
            sym = f"__print_symbolic(REC->kind, {pairs}), "
        doc_lines = [f"    /// rux:{name} — {doc[0]}"] + [f"    /// {l}" for l in doc[1:]]
        out.append("\n".join(doc_lines))
        if kinds:
            arms = "\n".join(f"            {k} => \"{v}\"," for k, v in kinds)
            kind_expr = f"""match args[0] {{
{arms}
            _ => "?",
        }}"""
        else:
            kind_expr = "args[0]"
        out.append(f"""    {ev} / {name}_fmt / trace_{name} :
        "rux", "{name}", {eid},
    print: "\\"kind=%s pid=%d a=%#lx b=%#lx\\", {sym}REC->kind, REC->pid, REC->a, REC->b",
    fields: "\\tfield:__u32 kind;\\toffset:8;\\tsize:4;\\tsigned:0;\\n\\
             \\tfield:pid_t pid;\\toffset:12;\\tsize:4;\\tsigned:1;\\n\\
             \\tfield:unsigned long a;\\toffset:16;\\tsize:8;\\tsigned:0;\\n\\
             \\tfield:unsigned long b;\\toffset:24;\\tsize:8;\\tsigned:0;\\n",
    call (kind: u32, pid: u32, a: u64, b: u64),
    render |args: &[u64; TRACE_ARGS]| {{
        let kind = {kind_expr};
        format!("kind={{}} pid={{}} a={{:#x}} b={{:#x}}", kind, args[1] as i32, args[2], args[3])
    }};
""")
    return "\n".join(out)


if __name__ == "__main__":
    sys.stdout.write(emit())
