fn expected_content_prefix() -> &'static [u8] {
    b"RUX-INITRD-TEST\n"
}

pub fn test_initrd() {
    test_group_start("initrd");

    // ---- Test 1: plain gzip (no optional header fields) ----
    match crate::initrd::gunzip(&GZ_PLAIN) {
        Ok(out) => {
            if out.len() == 3085 {
                test_pass("gunzip plain: size 3085");
            } else {
                test_fail("gunzip plain: size", &alloc::format!("got {}", out.len()));
            }
            if out.starts_with(expected_content_prefix()) {
                test_pass("gunzip plain: content prefix");
            } else {
                test_fail("gunzip plain: prefix", "mismatch");
            }
            if out.ends_with(b"END-MARKER-42") {
                test_pass("gunzip plain: content tail");
            } else {
                test_fail("gunzip plain: tail", "mismatch");
            }
            // middle entropy section: bytes 0..255 repeated 8x right after
            // the 17*64-byte repeating header
            let hdr = 16 * 64; // "RUX-INITRD-TEST\n" is 16 bytes
            let mut ok = true;
            for rep in 0..8 {
                for i in 0..256 {
                    if out[hdr + rep * 256 + i] != i as u8 {
                        ok = false;
                        break;
                    }
                }
            }
            if ok {
                test_pass("gunzip plain: entropy section");
            } else {
                test_fail("gunzip plain: entropy", "mismatch");
            }
        }
        Err(e) => test_fail("gunzip plain", e),
    }

    // ---- Test 2: gzip with FNAME (header-skip path) ----
    match crate::initrd::gunzip(&GZ_FNAME) {
        Ok(out) => {
            if out.len() == 3085 && out.ends_with(b"END-MARKER-42") {
                test_pass("gunzip FNAME: skipped name, content ok");
            } else {
                test_fail("gunzip FNAME", "wrong content");
            }
        }
        Err(e) => test_fail("gunzip FNAME", e),
    }

    // ---- Test 3: corruption rejection ----
    let mut corrupt = GZ_PLAIN;
    let mid = corrupt.len() / 2;
    corrupt[mid] ^= 0x55; // flip bits in the deflate body
    match crate::initrd::gunzip(&corrupt) {
        Ok(_) => test_fail("gunzip corrupt", "accepted corrupt stream"),
        Err(_) => test_pass("gunzip corrupt: rejected"),
    }
    // Truncated stream.
    match crate::initrd::gunzip(&GZ_PLAIN[..60]) {
        Ok(_) => test_fail("gunzip truncated", "accepted short stream"),
        Err(_) => test_pass("gunzip truncated: rejected"),
    }

    // ---- Test 4: cpio newc unpack into a fresh rootfs ----
    let sb = RootFSSuperBlock::new();
    match crate::initrd::unpack_newc(&CPIO_NEWC, &sb) {
        Ok(stats) => {
            let ok_counts = stats.files == 2
                && stats.dirs == 1
                && stats.symlinks == 1
                && stats.hardlinks == 1
                && stats.skipped_special == 1;
            if ok_counts {
                test_pass("cpio: stats counts");
            } else {
                test_fail(
                    "cpio: stats counts",
                    &alloc::format!(
                        "f={} d={} l={} h={} s={}",
                        stats.files, stats.dirs, stats.symlinks,
                        stats.hardlinks, stats.skipped_special
                    ),
                );
            }

            // File content.
            let check_read = |path: &str, want: &[u8], name: &str| {
                match sb.lookup(path) {
                    Some(node) => {
                        let mut buf = alloc::vec![0u8; want.len()];
                        let n = node.read_data(0, &mut buf);
                        if n == want.len() && buf.as_slice() == want {
                            test_pass(name);
                        } else {
                            test_fail(name, "content mismatch");
                        }
                    }
                    None => test_fail(name, "lookup failed"),
                }
            };
            check_read("/init", b"#!/s\n", "cpio: init content + mode");
            check_read("/dir/sub", b"hello world", "cpio: nested file content");

            // Hard link shares data with the first occurrence.
            check_read("/dir/hard", b"hello world", "cpio: hard link shares data");

            // Symlink target — via the parent directory: sb.lookup()
            // FOLLOWS symlinks and this target (../dir) exercises the
            // follower, not the link node itself.
            let link_node = sb
                .lookup("/dir")
                .and_then(|dir| dir.find_child(b"link"));
            match link_node {
                Some(node) => match node.get_link_target() {
                    Some(t) if t == b"../dir" => test_pass("cpio: symlink target"),
                    _ => test_fail("cpio: symlink target", "wrong target"),
                },
                None => test_fail("cpio: symlink target", "lookup failed"),
            }

            // Mode bits applied (init is 0755 from the archive).
            match sb.lookup("/init") {
                Some(node) => {
                    let mode = *node.mode.lock();
                    if mode & 0o777 == 0o755 {
                        test_pass("cpio: mode bits applied");
                    } else {
                        test_fail("cpio: mode bits", &alloc::format!("mode {:o}", mode & 0o777));
                    }
                }
                None => test_fail("cpio: mode bits", "lookup failed"),
            }
        }
        Err(e) => test_fail("cpio: unpack", e),
    }

    // ---- Test 5: bad archive rejected ----
    let sb2 = RootFSSuperBlock::new();
    match crate::initrd::unpack_newc(b"garbage!", &sb2) {
        Ok(_) => test_fail("cpio: garbage rejected", "accepted"),
        Err(_) => test_pass("cpio: garbage rejected"),
    }
}
