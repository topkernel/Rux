static uint32_t *fb; static int W,H,fbfd,cols,rows,cx,cy;
static uint8_t *scr; // 文本缓冲
static inline uint32_t rgb(int r,int g,int b){return ((uint32_t)r<<8)|((uint32_t)g<<16)|((uint32_t)b<<24);}
static void cell(int col,int row,uint8_t ch){ // 8x8 ×2 = 16x16
    uint32_t fg=rgb(220,225,230), bg=rgb(18,22,28);
    int x0=col*16, y0=row*16; const uint8_t*gl=F8[ch-32];
    for(int y=0;y<16;y+=2){uint8_t bits=gl[y/2];
        for(int x=0;x<16;x+=2){uint32_t c=(bits>>(7-x/2))&1?fg:bg;
            fb[(y0+y)*W+x0+x]=c; fb[(y0+y)*W+x0+x+1]=c;
            fb[(y0+y+1)*W+x0+x]=c; fb[(y0+y+1)*W+x0+x+1]=c;}}
}
static void redraw(void){for(int r=0;r<rows;r++)for(int c=0;c<cols;c++)cell(c,r,scr[r*cols+c]);
    ioctl(fbfd,FBIO_FLUSH,0);}
static void scroll1(void){memmove(scr,scr+cols,cols*(rows-1));
    memset(scr+cols*(rows-1),32,cols); cx=0; redraw();}
static void putch(uint8_t ch){
    if(ch=='\n'){cx=0;cy++; if(cy>=rows) scroll1(); else cell(cx,cy,' ');}
    else if(ch=='\r'){cx=0;}
    else if(ch=='\b'){if(cx>0)cx--; cell(cx,cy,' ');}
    else if(ch=='\t'){do{putch(' ');}while(cx%4); return;}
    else if(ch>=32&&ch<127){scr[cy*cols+cx]=ch; cell(cx,cy,ch); cx++;
        if(cx>=cols){cx=0;cy++;if(cy>=rows)scroll1();}}
    ioctl(fbfd,FBIO_FLUSH,0);}
static int esc=0;
static void term_out(uint8_t ch){
    if(esc){ if((ch>='a'&&ch<='z')||(ch>='A'&&ch<='Z')) esc=0; return; }
    if(ch==0x1b){esc=1;return;}
    putch(ch);}

int main(void){
    setvbuf(stdout,NULL,_IONBF,0);
    fbfd=open("/dev/fb0",O_RDWR);
    if(fbfd<0){printf("fbterm: no fb0\n");return 1;}
    struct fb_var v; memset(&v,0,sizeof v); ioctl(fbfd,FBIOGET_VSCREENINFO,&v);
    W=v.xres;H=v.yres;
    fb=mmap(0,(size_t)W*H*4,PROT_READ|PROT_WRITE,MAP_SHARED,fbfd,0);
    if(fb==MAP_FAILED){printf("fbterm: mmap fail\n");return 1;}
    cols=W/16; rows=H/16; cx=0; cy=0;
    scr=malloc(cols*rows); memset(scr,32,cols*rows);
    // 管道对挂 shell（pty 从节点 ENXIO 为独立遗留，管道路径已验证）
    int in_pipe[2], out_pipe[2];
    if(pipe(in_pipe)<0||pipe(out_pipe)<0){printf("fbterm: pipe fail\n");return 2;}
    int m=out_pipe[0];          // 从 shell 读
    int fwd=in_pipe[1];         // 写向 shell
    printf("fbterm: %dx%d term %dx%d (pipe mode)\n",W,H,cols,rows);
    pid_t pid=fork();
    if(pid==0){ setsid();
        dup2(in_pipe[0],0); dup2(out_pipe[1],1); dup2(out_pipe[1],2);
        char *av[]={"/bin/dash",NULL};
        char *ev[]={"HOME=/root","PATH=/bin:/usr/bin:/sbin","TERM=dumb",NULL};
        execve(av[0],av,ev); _exit(127); }
    close(in_pipe[0]); close(out_pipe[1]);
    // 结构：父进程=渲染器（阻塞读 shell 输出）；fork 输入子进程=阻塞读控制台并转发+本地回显。
    // 完全避开 fcntl(F_SETFL)（上个版本在此停摆）。
    putch('R');putch('u');putch('x');putch(' ');putch('T');putch('e');putch('r');putch('m');putch('\n');
    pid_t ipid=fork();
    if(ipid==0){
        uint8_t k;
        for(;;){
            ssize_t kn=read(0,&k,1);
            if(kn!=1) _exit(0);
            if(k=='\n'||k=='\r'){ write(fwd,"\n",1); putch('\n'); }
            else if(k==0x7f||k==8){ write(fwd,"\b",1); putch('\b'); }
            else { write(fwd,&k,1); putch(k); }
        }
    }
    uint8_t ob[512];
    for(;;){
        ssize_t n=read(m,ob,sizeof ob);
        if(n>0){ write(2,ob,n); for(ssize_t i=0;i<n;i++) term_out(ob[i]); }
        else if(n==0){ printf("fbterm: shell exited\n"); _exit(0); }
    }
}
