        [ $? != 0 ] && exit 0

        case $choice in
            1) memory_menu ;;
            2) smp_menu ;;
            3) scheduler_menu ;;
            4) network_menu ;;
            5) features_menu ;;
            6) drivers_menu ;;
            7) boot_menu ;;
            8) debug_menu ;;
            9) performance_menu ;;
            10) security_menu ;;
            11) show_config ;;
            12) save_and_exit ;;
