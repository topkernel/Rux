security_menu() {
    whiptail --title "Security Options" --msgbox "Security configuration:\n\nCurrently using default configuration from Kernel.toml" 10 50
}

show_config() {
    if [ -f "$CONFIG_FILE" ]; then
        whiptail --title "Current Configuration" --textbox "$CONFIG_FILE" 30 80
    else
        whiptail --title "Current Configuration" --msgbox "Not configured, using Kernel.toml defaults" 10 50
    fi
}

save_and_exit() {
    if whiptail --yesno "Save configuration to build/.config ?" 8 40; then
        generate_config
        rm -f "$CONFIG_BACKUP"
        echo "Configuration saved to build/.config"
        echo "Run 'make build' to compile kernel"
        exit 0
    fi
}

