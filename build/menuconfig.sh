}

main() {
    if ! command -v whiptail &> /dev/null; then
        echo "Error: whiptail not installed"
        echo "Run: sudo apt-get install whiptail"
        exit 1
    fi

    [ ! -f "$KERNEL_TOML" ] && echo "Error: configuration file not found" && exit 1

    # Backup existing configuration
    [ -f "$CONFIG_FILE" ] && cp "$CONFIG_FILE" "$CONFIG_BACKUP"

    whiptail --title "Rux Kernel Configuration" --msgbox \
        "Welcome to Rux kernel configuration system\n\n\
        Configuration will be saved to: build/.config\n\
        Use arrow keys to select options\n\
        Use Tab key to switch buttons\n\
        Use Enter to confirm selection\n\
        Use Esc to cancel operation" \
        12 60

    main_menu
}

main "$@"
